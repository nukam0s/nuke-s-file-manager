// Build pipeline: React build -> embed assets -> bundle server -> Node SEA single executable.
import { promises as fs } from 'node:fs'
import path from 'node:path'
import { execFileSync, execSync } from 'node:child_process'
import { createRequire } from 'node:module'

import { build as esbuild } from 'esbuild'

const require = createRequire(import.meta.url)
const { inject } = require('postject')

const root = process.cwd()
const distDir = path.join(root, 'dist')
const buildDir = path.join(root, 'build')
const serverDir = path.join(root, 'server')

const SEA_FUSE = 'NODE_SEA_FUSE_fce680ab2cc467b6e072b8b5df1996b2'

const MIME = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.ico': 'image/x-icon',
  '.woff2': 'font/woff2',
  '.txt': 'text/plain; charset=utf-8',
}

function npmBin() {
  return process.platform === 'win32' ? 'npm.cmd' : 'npm'
}

function relPosix(target) {
  return path.relative(root, target).split(path.sep).join('/')
}

async function walk(dir) {
  const output = []
  const entries = await fs.readdir(dir, { withFileTypes: true })
  for (const entry of entries) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) output.push(...(await walk(full)))
    else output.push(full)
  }
  return output
}

async function generateAssets() {
  const files = await walk(distDir)
  const assets = {}
  let indexHtml = ''

  for (const file of files) {
    const rel = '/' + path.relative(distDir, file).split(path.sep).join('/')
    if (rel === '/index.html') {
      indexHtml = await fs.readFile(file, 'utf8')
      continue
    }
    const data = await fs.readFile(file)
    assets[rel] = {
      type: MIME[path.extname(file)] || 'application/octet-stream',
      data: data.toString('base64'),
    }
  }

  // Inject the backend marker so the frontend talks HTTP instead of the mock.
  indexHtml = indexHtml.replace(
    '</head>',
    '<script>window.__FM_BACKEND__="http";</script></head>',
  )

  const output = [
    '// AUTO-GENERATED by scripts/build-sea.mjs — do not edit.',
    `export const ASSETS = ${JSON.stringify(assets)};`,
    `export const INDEX_HTML = ${JSON.stringify(indexHtml)};`,
    '',
  ].join('\n')

  await fs.writeFile(path.join(serverDir, 'assets.generated.js'), output, 'utf8')
  return Object.keys(assets).length
}

async function createPortableFolder() {
  const folder = path.join(buildDir, 'NukeFileManager-portable')
  await fs.mkdir(folder, { recursive: true })
  await fs.copyFile(process.execPath, path.join(folder, 'node.exe'))
  await fs.copyFile(path.join(buildDir, 'main.cjs'), path.join(folder, 'main.cjs'))
  const launcher = '@echo off\r\nstart "" "%~dp0node.exe" "%~dp0main.cjs"\r\n'
  await fs.writeFile(path.join(folder, 'Nuke File Manager.bat'), launcher, 'utf8')
  console.log(`   Fallback portable folder ready:\n   ${folder}`)
}

async function main() {
  console.log('[1/5] Building frontend (tsc + vite)...')
  execSync('npm run build', { cwd: root, stdio: 'inherit' })

  console.log('[2/5] Embedding dist assets...')
  const count = await generateAssets()
  console.log(`      embedded ${count} asset(s)`)

  console.log('[3/5] Bundling server with esbuild...')
  await fs.mkdir(buildDir, { recursive: true })
  await esbuild({
    entryPoints: [path.join(serverDir, 'main.js')],
    bundle: true,
    platform: 'node',
    format: 'cjs',
    target: 'node20',
    outfile: path.join(buildDir, 'main.cjs'),
    logLevel: 'info',
  })

  console.log('[4/5] Generating SEA blob...')
  const seaConfigPath = path.join(buildDir, 'sea-config.json')
  const blobPath = path.join(buildDir, 'sea-prep.blob')
  const seaConfig = {
    main: relPosix(path.join(buildDir, 'main.cjs')),
    output: relPosix(blobPath),
    disableExperimentalSEAWarning: true,
    useSnapshot: false,
    useCodeCache: false,
    assets: {},
  }
  await fs.writeFile(seaConfigPath, JSON.stringify(seaConfig, null, 2), 'utf8')
  execFileSync(process.execPath, ['--experimental-sea-config', seaConfigPath], {
    cwd: root,
    stdio: 'inherit',
  })

  console.log('[5/5] Creating portable executable...')
  const exePath = path.join(buildDir, 'NukeFileManager.exe')
  await fs.copyFile(process.execPath, exePath)
  const blob = await fs.readFile(blobPath)

  try {
    await inject(exePath, 'NODE_SEA_BLOB', blob, { sentinelFuse: SEA_FUSE })
    console.log(`\nPortable single executable ready:\n   ${exePath}`)
  } catch (error) {
    console.warn(`\nSEA injection failed (${error.message}). Falling back to a portable folder.`)
    await fs.rm(exePath, { force: true })
    await createPortableFolder()
  }
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})
