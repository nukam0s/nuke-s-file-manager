// Electron build pipeline: React build -> embed assets -> bundle server (CJS) for the Electron main process.
import { promises as fs } from 'node:fs'
import path from 'node:path'

import { build as esbuild } from 'esbuild'

const root = process.cwd()
const distDir = path.join(root, 'dist')
const buildDir = path.join(root, 'build')
const serverDir = path.join(root, 'server')

const MIME = {
  '.html': 'text/html; charset=utf-8',
  '.js': 'text/javascript; charset=utf-8',
  '.css': 'text/css; charset=utf-8',
  '.json': 'application/json; charset=utf-8',
  '.svg': 'image/svg+xml',
  '.png': 'image/png',
  '.ico': 'image/x-icon',
  '.woff2': 'font/woff2',
  '.txt': 'text/plain; charset=utf-8',
}

async function walk(dir) {
  const output = []
  const entries = await fs.readdir(dir, { withFileTypes: true })
  for (const entry of entries) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) output.push(...(await walk(full)))
    else output.push(full)
  }
  return output
}

async function generateAssets() {
  const files = await walk(distDir)
  const assets = {}
  let indexHtml = ''

  for (const file of files) {
    const rel = '/' + path.relative(distDir, file).split(path.sep).join('/')
    if (rel === '/index.html') {
      indexHtml = await fs.readFile(file, 'utf8')
      continue
    }
    const data = await fs.readFile(file)
    assets[rel] = {
      type: MIME[path.extname(file)] || 'application/octet-stream',
      data: data.toString('base64'),
    }
  }

  // Inject the backend marker so the frontend talks HTTP instead of the mock.
  indexHtml = indexHtml.replace(
    '</head>',
    '<script>window.__FM_BACKEND__="http";</script></head>',
  )

  const output = [
    '// AUTO-GENERATED by scripts/bundle-server.mjs — do not edit.',
    `export const ASSETS = ${JSON.stringify(assets)};`,
    `export const INDEX_HTML = ${JSON.stringify(indexHtml)};`,
    '',
  ].join('\n')

  await fs.writeFile(path.join(serverDir, 'assets.generated.js'), output, 'utf8')
  return Object.keys(assets).length
}

async function main() {
  console.log('[1/2] Embedding dist assets...')
  const count = await generateAssets()
  console.log(`      embedded ${count} asset(s)`)

  console.log('[2/2] Bundling server with esbuild...')
  await fs.mkdir(buildDir, { recursive: true })
  await esbuild({
    entryPoints: [path.join(serverDir, 'main.js')],
    bundle: true,
    platform: 'node',
    format: 'cjs',
    target: 'node20',
    outfile: path.join(buildDir, 'server.cjs'),
    logLevel: 'info',
  })

  console.log(`\nElectron server bundle ready:\n   ${path.join(buildDir, 'server.cjs')}`)
}

main().catch((error) => {
  console.error(error)
  process.exit(1)
})
